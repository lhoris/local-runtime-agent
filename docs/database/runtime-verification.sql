-- Local Runtime Agent 동작 확인 SQL
-- 애플리케이션을 기동한 뒤 아래 블록을 순서대로 실행합니다.
-- @local_ip는 현재 Agent가 실행 중인 PC의 실제 IP로 변경합니다.

SET @local_ip = '192.168.0.7';

-- Java/Hibernate와 MariaDB의 시간대 기준 확인
SELECT @@global.time_zone AS GLOBAL_TIME_ZONE,
       @@session.time_zone AS SESSION_TIME_ZONE,
       NOW() AS DB_LOCAL_TIME,
       UTC_TIMESTAMP() AS DB_UTC_TIME;

-- 1. 로컬 IP로 Agent가 등록되었는지 확인
SELECT '1_AGENT' AS STEP,
       AGENT_ID,
       HOSTNAME,
       IP_ADDRESS,
       INSTALLED_AT,
       WORKED_AT,
       CASE WHEN IP_ADDRESS = @local_ip THEN '정상' ELSE 'IP 확인 필요' END AS RESULT
FROM TB_M26_AGENT
WHERE IP_ADDRESS = @local_ip;

SET @agent_id = (
    SELECT AGENT_ID
    FROM TB_M26_AGENT
    WHERE IP_ADDRESS = @local_ip
    ORDER BY AGENT_ID
    LIMIT 1
);

-- 2. 해당 Agent에 연결된 감시 대상과 프로젝트 디렉토리 확인
SELECT '2_MODEL_PROCESS' AS STEP,
       MODEL_PROCESS_ID,
       AGENT_ID,
       MODEL_NAME,
       PYTHON_PROJECT_PATH,
       PROCESS_STATUS,
       PROCESS_PID,
       HEALTH_STATUS
FROM TB_M26_MODEL_PROCESS
WHERE AGENT_ID = @agent_id
ORDER BY MODEL_PROCESS_ID;

-- 3. heartbeat가 최근 주기마다 갱신되는지 확인
SELECT '3_HEARTBEAT' AS STEP,
       MODEL_PROCESS_ID,
       PROCESS_STATUS,
       PROCESS_PID,
       LAST_HEARTBEAT,
       TIMESTAMPDIFF(SECOND, LAST_HEARTBEAT, CURRENT_TIMESTAMP()) AS HEARTBEAT_AGE_SEC,
       CASE
           WHEN LAST_HEARTBEAT IS NULL THEN 'heartbeat 없음'
           WHEN TIMESTAMPDIFF(SECOND, LAST_HEARTBEAT, CURRENT_TIMESTAMP()) <= 90 THEN '정상'
           ELSE 'heartbeat 지연'
       END AS RESULT
FROM TB_M26_MODEL_PROCESS
WHERE AGENT_ID = @agent_id
ORDER BY MODEL_PROCESS_ID;

-- 4. START/STOP/RESTART 명령의 처리 결과 확인
SELECT '4_COMMAND' AS STEP,
       COMMAND_ID,
       MODEL_PROCESS_ID AS TARGET_MODEL_PROCESS_ID,
       COMMAND_TYPE,
       COMMAND_STATUS,
       CREATED_TIMESTAMP,
       PROCESSED_AT,
       FAILED_REASON
FROM TB_M26_COMMAND
WHERE AGENT_ID = @agent_id
ORDER BY CREATED_TIMESTAMP DESC
LIMIT 20;

-- 5. 명령 실행 이력 확인
SELECT '5_EXECUTION_LOG' AS STEP,
       LOG_ID,
       MODEL_PROCESS_ID AS TARGET_MODEL_PROCESS_ID,
       COMMAND_TYPE,
       EXECUTION_STATUS,
       EXIT_CODE,
       DURATION_SEC,
       CREATED_TIMESTAMP,
       STDERR_PREVIEW
FROM TB_M26_EXECUTION_LOG
WHERE AGENT_ID = @agent_id
ORDER BY CREATED_TIMESTAMP DESC
LIMIT 20;

-- 6. 최종 요약
SELECT '6_SUMMARY' AS STEP,
       a.AGENT_ID,
       a.IP_ADDRESS,
       COUNT(p.MODEL_PROCESS_ID) AS MONITORED_PROCESS_COUNT,
       SUM(CASE WHEN p.PROCESS_STATUS = 'RUNNING' THEN 1 ELSE 0 END) AS RUNNING_COUNT,
       MAX(p.LAST_HEARTBEAT) AS LAST_HEARTBEAT
FROM TB_M26_AGENT a
LEFT JOIN TB_M26_MODEL_PROCESS p ON p.AGENT_ID = a.AGENT_ID
WHERE a.AGENT_ID = @agent_id
GROUP BY a.AGENT_ID, a.IP_ADDRESS;
