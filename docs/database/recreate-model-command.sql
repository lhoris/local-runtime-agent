-- TB_M26_MODEL_COMMAND 재생성 스크립트
-- 주의: 해당 테이블의 기존 명령 이력이 모두 삭제됩니다.

DROP TABLE IF EXISTS TB_M26_MODEL_COMMAND;

CREATE TABLE TB_M26_MODEL_COMMAND (
    CREATED_OBJECT_TYPE VARCHAR(1) COMMENT '생성 객체 구분',
    CREATED_OBJECT_ID VARCHAR(22) COMMENT '생성 객체 식별자',
    CREATED_PROGRAM_ID VARCHAR(22) COMMENT '생성 프로그램 식별자',
    CREATED_TIMESTAMP TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '생성 일시',
    LAST_UPDATED_OBJECT_TYPE VARCHAR(1) COMMENT '최종 수정 객체 구분',
    LAST_UPDATED_OBJECT_ID VARCHAR(22) COMMENT '최종 수정 객체 식별자',
    LAST_UPDATED_PROGRAM_ID VARCHAR(22) COMMENT '최종 수정 프로그램 식별자',
    LAST_UPDATED_TIMESTAMP TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '최종 수정 일시',
    DATA_END_STATUS VARCHAR(1) DEFAULT 'N' COMMENT '데이터 종료 여부',
    DATA_END_OBJECT_TYPE VARCHAR(1) COMMENT '데이터 종료 객체 구분',
    DATA_END_OBJECT_ID VARCHAR(22) COMMENT '데이터 종료 객체 식별자',
    DATA_END_PROGRAM_ID VARCHAR(22) COMMENT '데이터 종료 프로그램 식별자',
    DATA_END_TIMESTAMP TIMESTAMP NULL COMMENT '데이터 종료 일시',
    COMMAND_ID VARCHAR(64) NOT NULL COMMENT '명령 식별자',
    AGENT_ID VARCHAR(64) NOT NULL COMMENT '명령 대상 Agent 식별자',
    MODEL_PROCESS_ID VARCHAR(64) COMMENT '명령 대상 모델 프로세스 식별자',
    COMMAND_TYPE VARCHAR(32) COMMENT '명령 유형: START, STOP, RESTART 또는 사용자 정의 명령',
    COMMAND_STATUS VARCHAR(32) COMMENT '명령 상태: PENDING, COMPLETED, FAILED',
    COMMAND_PARAMETERS LONGTEXT COMMENT '명령 파라미터 JSON 문자열',
    PROCESSED_AT TIMESTAMP NULL COMMENT '명령 처리 완료 일시',
    FAILED_REASON LONGTEXT COMMENT '명령 실패 사유',
    PRIMARY KEY (COMMAND_ID)
) COMMENT='AI 모델 프로세스 제어 명령 큐';

CREATE INDEX IDX_M26_MODEL_COMMAND_PENDING
    ON TB_M26_MODEL_COMMAND (AGENT_ID, COMMAND_STATUS);
