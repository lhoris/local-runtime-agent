LEFT JOIN information_schema.COLUMNS actual
    ON actual.TABLE_SCHEMA = DATABASE()
   AND actual.TABLE_NAME = required_columns.TABLE_NAME
   AND actual.COLUMN_NAME = required_columns.COLUMN_NAME
ORDER BY required_columns.TABLE_NAME, required_columns.COLUMN_NAME;

-- Every shared table must contain the common 14-column audit contract.
SELECT audit_tables.TABLE_NAME,
       audit_columns.COLUMN_NAME,
       CASE WHEN actual.COLUMN_NAME IS NULL THEN 'MISSING' ELSE 'OK' END AS AUDIT_COLUMN_STATUS
FROM (
    SELECT 'TB_M26_AGENT' AS TABLE_NAME
    UNION ALL SELECT 'TB_M26_MODEL_PROCESS'
    UNION ALL SELECT 'TB_M26_COMMAND'
    UNION ALL SELECT 'TB_M26_MODEL_PARAMETER'
    UNION ALL SELECT 'TB_M26_EXECUTION_LOG'
) audit_tables
CROSS JOIN (
    SELECT 'CREATED_OBJECT_TYPE' AS COLUMN_NAME
    UNION ALL SELECT 'CREATED_OBJECT_ID'
    UNION ALL SELECT 'CREATED_PROGRAM_ID'
    UNION ALL SELECT 'CREATED_TIMESTAMP'
    UNION ALL SELECT 'LAST_UPDATED_OBJECT_TYPE'
    UNION ALL SELECT 'LAST_UPDATED_OBJECT_ID'
    UNION ALL SELECT 'LAST_UPDATED_PROGRAM_ID'
    UNION ALL SELECT 'LAST_UPDATED_TIMESTAMP'
    UNION ALL SELECT 'DATA_END_STATUS'
    UNION ALL SELECT 'DATA_END_OBJECT_TYPE'
    UNION ALL SELECT 'DATA_END_OBJECT_ID'
    UNION ALL SELECT 'DATA_END_PROGRAM_ID'
    UNION ALL SELECT 'DATA_END_TIMESTAMP'
) audit_columns
LEFT JOIN information_schema.COLUMNS actual
    ON actual.TABLE_SCHEMA = DATABASE()
   AND actual.TABLE_NAME = audit_tables.TABLE_NAME
   AND actual.COLUMN_NAME = audit_columns.COLUMN_NAME
ORDER BY audit_tables.TABLE_NAME, audit_columns.COLUMN_NAME;

-- One IP must identify one Agent. Resolve duplicates before starting an Agent.
SELECT IP_ADDRESS,
       COUNT(*) AS AGENT_COUNT,
       GROUP_CONCAT(AGENT_ID ORDER BY AGENT_ID) AS AGENT_IDS
FROM TB_M26_AGENT
WHERE IP_ADDRESS IS NOT NULL
  AND IP_ADDRESS <> ''
GROUP BY IP_ADDRESS
HAVING COUNT(*) > 1;

-- Every process row must point to an existing Agent and contain a project directory.
SELECT p.MODEL_PROCESS_ID,
       p.AGENT_ID,
       CASE WHEN a.AGENT_ID IS NULL THEN 'MISSING_AGENT' ELSE 'OK' END AS AGENT_STATUS,
       CASE WHEN p.PYTHON_PROJECT_PATH IS NULL OR p.PYTHON_PROJECT_PATH = ''
            THEN 'MISSING_PROJECT_PATH' ELSE 'OK' END AS PROJECT_PATH_STATUS
FROM TB_M26_MODEL_PROCESS p
LEFT JOIN TB_M26_AGENT a ON a.AGENT_ID = p.AGENT_ID
ORDER BY p.MODEL_PROCESS_ID;
