FROM (
    SELECT 'TB_M26_AGENT' AS TABLE_NAME, 'AGENT_ID' AS COLUMN_NAME
    UNION ALL SELECT 'TB_M26_AGENT', 'IP_ADDRESS'
    UNION ALL SELECT 'TB_M26_MODEL_PROCESS', 'MODEL_PROCESS_ID'
    UNION ALL SELECT 'TB_M26_MODEL_PROCESS', 'PROCESS_AREA_CODE'
    UNION ALL SELECT 'TB_M26_MODEL_PROCESS', 'AUTOMATION_NAME'
    UNION ALL SELECT 'TB_M26_MODEL_PROCESS', 'SERVER_IP'
    UNION ALL SELECT 'TB_M26_MODEL_PROCESS', 'PYTHON_PROJECT_PATH'
    UNION ALL SELECT 'TB_M26_MODEL_PROCESS', 'PROCESS_STATUS'
    UNION ALL SELECT 'TB_M26_MODEL_PROCESS', 'MONITORING_STATUS'
    UNION ALL SELECT 'TB_M26_MODEL_PROCESS', 'CONTROL_STATUS'
