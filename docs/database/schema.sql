DROP TABLE TB_M26_AGENT;
CREATE TABLE IF NOT EXISTS TB_M26_AGENT (
    CREATED_OBJECT_TYPE VARCHAR(1) COMMENT '생성 객체 구분',
    CREATED_OBJECT_ID VARCHAR(22) COMMENT '생성 객체 식별자',
    CREATED_PROGRAM_ID VARCHAR(22) COMMENT '생성 프로그램 식별자',
    CREATED_TIMESTAMP TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '생성 일시',
    LAST_UPDATED_OBJECT_TYPE VARCHAR(1) COMMENT '최종 수정 객체 구분',
    LAST_UPDATED_OBJECT_ID VARCHAR(22) COMMENT '최종 수정 객체 식별자',
    LAST_UPDATED_PROGRAM_ID VARCHAR(22) COMMENT '최종 수정 프로그램 식별자',
    LAST_UPDATED_TIMESTAMP TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '최종 수정 일시',
    DATA_END_STATUS VARCHAR(1) DEFAULT 'N' COMMENT '데이터 종료 여부',
    DATA_END_OBJECT_TYPE VARCHAR(1) COMMENT '데이터 종료 객체 구분',
    DATA_END_OBJECT_ID VARCHAR(22) COMMENT '데이터 종료 객체 식별자',
    DATA_END_PROGRAM_ID VARCHAR(22) COMMENT '데이터 종료 프로그램 식별자',
    DATA_END_TIMESTAMP TIMESTAMP NULL COMMENT '데이터 종료 일시',

    AGENT_ID VARCHAR(64) PRIMARY KEY COMMENT 'Agent 고유 식별자',
    HOSTNAME VARCHAR(256) COMMENT 'Agent가 실행되는 호스트명',
    OS_TYPE VARCHAR(32) COMMENT '운영체제 종류',
    IP_ADDRESS VARCHAR(45) COMMENT 'Agent 식별에 사용하는 로컬 IP 주소',
    INSTALLED_AT TIMESTAMP NULL COMMENT 'Agent 최초 등록 일시',
    WORKED_AT TIMESTAMP NULL COMMENT 'Agent가 마지막 루프를 수행한 일시'
) COMMENT='에이전트';

DROP TABLE TB_M26_MODEL_PROCESS;
CREATE TABLE IF NOT EXISTS TB_M26_MODEL_PROCESS (
    CREATED_OBJECT_TYPE VARCHAR(1) COMMENT '생성 객체 구분',
    CREATED_OBJECT_ID VARCHAR(22) COMMENT '생성 객체 식별자',
    CREATED_PROGRAM_ID VARCHAR(22) COMMENT '생성 프로그램 식별자',
    CREATED_TIMESTAMP TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '생성 일시',
    LAST_UPDATED_OBJECT_TYPE VARCHAR(1) COMMENT '최종 수정 객체 구분',
    LAST_UPDATED_OBJECT_ID VARCHAR(22) COMMENT '최종 수정 객체 식별자',
    LAST_UPDATED_PROGRAM_ID VARCHAR(22) COMMENT '최종 수정 프로그램 식별자',
    LAST_UPDATED_TIMESTAMP TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '최종 수정 일시',
    DATA_END_STATUS VARCHAR(1) DEFAULT 'N' COMMENT '데이터 종료 여부',
    DATA_END_OBJECT_TYPE VARCHAR(1) COMMENT '데이터 종료 객체 구분',
    DATA_END_OBJECT_ID VARCHAR(22) COMMENT '데이터 종료 객체 식별자',
    DATA_END_PROGRAM_ID VARCHAR(22) COMMENT '데이터 종료 프로그램 식별자',
    DATA_END_TIMESTAMP TIMESTAMP NULL COMMENT '데이터 종료 일시',

    -- vision-monitor와 공유하는 프로세스 기준 정보
    MODEL_PROCESS_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY COMMENT '모델 프로세스 고유 식별자',
    AGENT_ID VARCHAR(64) NULL COMMENT '이 프로세스를 담당하는 Agent 식별자',
    SERVER_IP VARCHAR(45) COMMENT '프로세스가 실행되는 서버 IP 주소',
    MODEL_NAME VARCHAR(256) COMMENT '모델 또는 프로세스 이름',
    AUTOMATION_NAME VARCHAR(256) COMMENT '자동화 이름',
    PROCESS_AREA_CODE VARCHAR(64) COMMENT '프로세스 영역 코드',
    PYTHON_PROJECT_PATH VARCHAR(512) COMMENT 'start.bat, stop.bat, restart.bat가 있는 Python 프로젝트 경로',
    PYTHON_COMMAND VARCHAR(1024) COMMENT '실행 중인 Python 프로세스 식별용 명령줄(예: main.py --port 9001)',
    PROCESS_STATUS VARCHAR(32) COMMENT '프로세스 실행 상태',
    MONITORING_STATUS VARCHAR(32) COMMENT '프로세스 모니터링 상태',
    CONTROL_STATUS VARCHAR(32) COMMENT '프로세스 제어 상태',
    LAST_STATUS_TIMESTAMP TIMESTAMP NULL COMMENT '프로세스 상태가 마지막으로 변경된 일시',
    DESCRIPTION LONGTEXT COMMENT '프로세스 설명',

    -- Agent가 관리하는 실행 및 운영 상태
    AUTO_RESTART BOOLEAN DEFAULT TRUE COMMENT '비정상 종료 시 자동 재시작 여부',
    MAX_RESTART_ATTEMPTS INT DEFAULT 3 COMMENT '자동 재시작 최대 시도 횟수',
    RESTART_DELAY_SEC INT DEFAULT 10 COMMENT '재시작 전 대기 시간(초)',
    TIMEOUT_SEC INT DEFAULT 3600 COMMENT '프로세스 제어 작업 제한 시간(초)',
    HEALTH_CHECK_ENABLED BOOLEAN DEFAULT TRUE COMMENT '헬스체크 사용 여부',
    HEALTH_CHECK_INTERVAL_SEC INT DEFAULT 30 COMMENT '헬스체크 주기(초)',
    HEALTH_CHECK_ENDPOINT VARCHAR(512) COMMENT '선택적 로컬 헬스체크 엔드포인트',
    PROCESS_PID INT COMMENT '최근 확인된 운영체제 프로세스 ID',
    LAST_HEALTH_CHECK TIMESTAMP NULL COMMENT '최근 헬스체크 일시',
    LAST_HEARTBEAT TIMESTAMP NULL COMMENT '최근 프로세스 상태 저장 일시',
    HEALTH_STATUS VARCHAR(32) COMMENT '최근 헬스체크 결과',
    UPTIME_SEC BIGINT COMMENT '최근 확인된 프로세스 실행 시간(초)',
    ERROR_MESSAGE LONGTEXT COMMENT '최근 프로세스 또는 헬스체크 오류 메시지'
    ) COMMENT='모델프로세스';

