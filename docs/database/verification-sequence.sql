-- Local Runtime Agent main-function verification sequence for MariaDB.
-- Run each numbered block after the previous block has completed.
-- Replace the IP and Python command values before running.

-- 0. Select the Agent created by the running application.
SET @local_ip = '192.168.0.7';
SET @agent_id = (
    SELECT AGENT_ID
    FROM TB_M26_AGENT
    WHERE IP_ADDRESS = @local_ip
    ORDER BY AGENT_ID
    LIMIT 1
);

SELECT '0_AGENT' AS STEP,
       @agent_id AS AGENT_ID,
       @local_ip AS EXPECTED_IP,
       CASE WHEN @agent_id IS NULL THEN 'FAIL' ELSE 'OK' END AS RESULT;

SELECT AGENT_ID, HOSTNAME, OS_TYPE, IP_ADDRESS, INSTALLED_AT
FROM TB_M26_AGENT
WHERE AGENT_ID = @agent_id;

-- 1. Register the Python process definition.
-- PROCESS_ID is the stable logical ID. PROCESS_PID is filled by the Agent later.
SET @process_id = 'python-smoke-01';

INSERT INTO TB_M26_MODEL_PROCESS (
    PROCESS_ID, AGENT_ID, MODEL_NAME, MODEL_TYPE,
    EXECUTABLE_PATH, WORKING_DIRECTORY, COMMAND_ARGS, ENV_VARS,
    AUTO_RESTART, MAX_RESTART_ATTEMPTS, RESTART_DELAY_SEC,
    HEALTH_CHECK_ENABLED, HEALTH_CHECK_INTERVAL_SEC,
    PROCESS_STATE, CRASH_COUNT
) VALUES (
    @process_id, @agent_id, 'Python smoke process', 'PYTHON',
    'C:/Python312/python.exe', 'C:/workspace/python-smoke',
    JSON_ARRAY('C:/workspace/python-smoke/smoke.py'), JSON_OBJECT(),
    TRUE, 3, 10, TRUE, 30, 'STOPPED', 0
)
ON DUPLICATE KEY UPDATE
    AGENT_ID = VALUES(AGENT_ID),
    EXECUTABLE_PATH = VALUES(EXECUTABLE_PATH),
    WORKING_DIRECTORY = VALUES(WORKING_DIRECTORY),
    COMMAND_ARGS = VALUES(COMMAND_ARGS),
    ENV_VARS = VALUES(ENV_VARS),
    AUTO_RESTART = VALUES(AUTO_RESTART),
    MAX_RESTART_ATTEMPTS = VALUES(MAX_RESTART_ATTEMPTS),
    RESTART_DELAY_SEC = VALUES(RESTART_DELAY_SEC),
    HEALTH_CHECK_ENABLED = VALUES(HEALTH_CHECK_ENABLED),
    HEALTH_CHECK_INTERVAL_SEC = VALUES(HEALTH_CHECK_INTERVAL_SEC);

SELECT '1_DEFINITION' AS STEP, PROCESS_ID, AGENT_ID, EXECUTABLE_PATH,
       COMMAND_ARGS, PROCESS_STATE, PROCESS_PID
FROM TB_M26_MODEL_PROCESS
WHERE PROCESS_ID = @process_id;

-- 2. Ask the Agent to start it.
INSERT INTO TB_M26_COMMAND (
    COMMAND_ID, AGENT_ID, PROCESS_ID, COMMAND_TYPE,
    COMMAND_STATUS, COMMAND_PARAMETERS
) VALUES (
    UUID(), @agent_id, @process_id, 'START', 'PENDING', JSON_OBJECT()
);

-- Wait for one polling cycle, then inspect the command and runtime row.
SELECT '2_START_COMMAND' AS STEP, COMMAND_ID, PROCESS_ID,
       COMMAND_STATUS, PROCESSED_AT, FAILED_REASON
FROM TB_M26_COMMAND
WHERE AGENT_ID = @agent_id AND PROCESS_ID = @process_id
ORDER BY PROCESSED_AT DESC, COMMAND_ID DESC
LIMIT 1;

SELECT '2_RUNNING_STATE' AS STEP, PROCESS_ID, PROCESS_STATE, PROCESS_PID,
       LAST_HEALTH_CHECK, LAST_HEARTBEAT, HEALTH_STATUS, UPTIME_SEC
FROM TB_M26_MODEL_PROCESS
WHERE PROCESS_ID = @process_id;

-- 3. Stop it and verify the command result and persisted state.
INSERT INTO TB_M26_COMMAND (
    COMMAND_ID, AGENT_ID, PROCESS_ID, COMMAND_TYPE,
    COMMAND_STATUS, COMMAND_PARAMETERS
) VALUES (
    UUID(), @agent_id, @process_id, 'STOP', 'PENDING', JSON_OBJECT()
);

SELECT '3_STOP_STATE' AS STEP, PROCESS_ID, PROCESS_STATE, PROCESS_PID,
       LAST_HEARTBEAT
FROM TB_M26_MODEL_PROCESS
WHERE PROCESS_ID = @process_id;

-- 4. Start it again through RESTART and inspect the execution history.
INSERT INTO TB_M26_COMMAND (
    COMMAND_ID, AGENT_ID, PROCESS_ID, COMMAND_TYPE,
    COMMAND_STATUS, COMMAND_PARAMETERS
) VALUES (
    UUID(), @agent_id, @process_id, 'RESTART', 'PENDING', JSON_OBJECT()
);

SELECT '4_EXECUTION_LOG' AS STEP, PROCESS_ID, COMMAND_TYPE,
       EXECUTION_STATUS, EXIT_CODE, DURATION_SEC, CREATED_TIMESTAMP
FROM TB_M26_EXECUTION_LOG
WHERE AGENT_ID = @agent_id AND PROCESS_ID = @process_id
ORDER BY CREATED_TIMESTAMP DESC
LIMIT 10;

-- 5. Final compact check for the process and Agent heartbeat.
SELECT '5_FINAL_CHECK' AS STEP,
       p.PROCESS_ID,
       p.PROCESS_STATE,
       p.PROCESS_PID,
       p.LAST_HEARTBEAT,
       CASE
           WHEN p.PROCESS_STATE = 'RUNNING' AND p.PROCESS_PID IS NOT NULL
           THEN 'OK'
           ELSE 'CHECK'
       END AS RESULT
FROM TB_M26_MODEL_PROCESS p
WHERE p.PROCESS_ID = @process_id
  AND p.AGENT_ID = @agent_id;

-- Manual alternative: attach a process that was started outside the Agent.
-- The Agent searches live OS processes using EXECUTABLE_PATH and COMMAND_ARGS.
-- It updates PROCESS_PID only when a matching process is found.
INSERT INTO TB_M26_COMMAND (
    COMMAND_ID, AGENT_ID, PROCESS_ID, COMMAND_TYPE,
    COMMAND_STATUS, COMMAND_PARAMETERS
) VALUES (
    UUID(), @agent_id, @process_id, 'ATTACH', 'PENDING', JSON_OBJECT()
);

SELECT '6_ATTACH_RESULT' AS STEP, COMMAND_ID, COMMAND_STATUS,
       PROCESSED_AT, FAILED_REASON
FROM TB_M26_COMMAND
WHERE AGENT_ID = @agent_id
  AND PROCESS_ID = @process_id
  AND COMMAND_TYPE = 'ATTACH'
ORDER BY COMMAND_ID DESC
LIMIT 1;

SELECT '6_ATTACHED_PROCESS' AS STEP, PROCESS_ID, PROCESS_STATE, PROCESS_PID,
       LAST_HEARTBEAT
FROM TB_M26_MODEL_PROCESS
WHERE PROCESS_ID = @process_id;
